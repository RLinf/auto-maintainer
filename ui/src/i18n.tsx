const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "zh", setLang: () => {} });

let active: Lang = "zh";

/** The language in use, for code outside React components (relative times). */
export function currentLang(): Lang {
  return active;
}

function readLang(): Lang {
  try {
    return localStorage.getItem("am.lang") === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  active = lang;
  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("am.lang", l);
    } catch {
      // storage can be unavailable; the choice then lasts for this page only
    }
  };
  return <LangContext.Provider value={{ lang, setLang }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

export function useT(): (text: string) => string {
  const { lang } = useLang();
  return (text: string) => (lang === "zh" ? (zh[text] ?? text) : text);
}
